#include <cstdio>
#include <cstdlib>

// Helix internal diagnostic gate. Requires the correct HELIX_SEED to release
// a maintenance hint. The expected seed is NOT stored as text -- it is
// computed at runtime from the constants below. The hint is XOR-obfuscated so
// `strings` reveals nothing; it only decodes when the correct seed is supplied.
//
// There is NO flag here by design: the decoded text points at the next hop
// of the local-escalation chain. Keep it that way.
int main() {
    const char* env = getenv("HELIX_SEED");
    if (!env) { printf("[-] HELIX_SEED not set. Denied.\n"); return 1; }
    long seed = strtol(env, nullptr, 10);

    long a = 0x5EED;
    long b = (a << 1) ^ 0x1234;
    long expected = b - 0x0777 + 42;      // the gate: seed must equal this

    if (seed != expected) {
        printf("[-] Invalid seed. Access denied.\n");
        return 1;
    }

    unsigned char key = (unsigned char)(seed & 0xFF);
    unsigned char enc[] = { 0xf5,0xc9,0xc4,0x81,0xce,0xd1,0xd2,0x81,0xc5,0xc4,0xd2,0xca,0x81,0xcf,0xc4,0xd7,0xc4,0xd3,0x81,0xcd,0xce,0xc6,0xd2,0x81,0xce,0xd4,0xd5,0x8f,0x81,0xe8,0xd5,0xd2,0x81,0xd5,0xc4,0xd3,0xcc,0xc8,0xcf,0xc0,0xcd,0x81,0xd2,0xc4,0xd2,0xd2,0xc8,0xce,0xcf,0x81,0xc8,0xd2,0x81,0xd2,0xc9,0xc0,0xd3,0xc4,0xc5,0x81,0x8c,0x81,0xcb,0xce,0xc8,0xcf,0x81,0xd5,0xc9,0xc4,0x81,0xc2,0xce,0xcf,0xd7,0xc4,0xd3,0xd2,0xc0,0xd5,0xc8,0xce,0xcf,0x8f,0x81,0xe8,0xcf,0xc2,0xc8,0xc5,0xc4,0xcf,0xd5,0x81,0xcd,0xce,0xc6,0xc6,0xc4,0xc5,0x8f,0x81,0x8c,0x81,0xec,0xe6,0xec,0xf5 };
    int n = (int)sizeof(enc);
    printf("[+] Seed accepted. Hint: ");
    for (int i = 0; i < n; i++) putchar(enc[i] ^ key);
    putchar('\n');
    return 0;
}
